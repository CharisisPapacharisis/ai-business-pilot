"""Check an approved, duplicate-aware Linear issue creation workflow."""

import argparse
import asyncio
import json
from pathlib import Path
from uuid import uuid4

from langgraph.checkpoint.sqlite.aio import AsyncSqliteSaver
from langgraph.types import Command

from ai_business_pilot.approval import LinearIssueDraft, build_approval_graph
from ai_business_pilot.fixture_config import LINEAR_DEFAULT_TEAM
from ai_business_pilot.mcp_client import create_mcp_adapter

PROJECT_ROOT = Path(__file__).resolve().parents[1]
CHECKPOINT_DB = PROJECT_ROOT / "storage" / "approval_workflow.sqlite"


def parse_args() -> argparse.Namespace:
    """Parse a start or resume command."""
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)

    start = commands.add_parser("start", help="Prepare and pause a demo issue")
    start.add_argument(
        "--thread-id",
        default=None,
        help="Optional ID for repeatable testing; a unique ID is generated by default",
    )

    resume = commands.add_parser("resume", help="Resume a paused request")
    resume.add_argument(
        "thread_id",
        nargs="?",
        help="Thread ID to resume; defaults to the latest paused request",
    )
    resume.add_argument(
        "decision",
        nargs="?",
        choices=("approve", "reject"),
        help="Optional non-interactive decision",
    )
    return parser.parse_args()


def print_heading(title: str) -> None:
    """Print a visible terminal section heading."""
    print(f"\n{'=' * 60}\n{title}\n{'=' * 60}")


def demo_draft(request_id: str) -> LinearIssueDraft:
    """Create one unmistakably labeled issue draft for write testing."""
    return LinearIssueDraft(
        request_id=request_id,
        title=f"[AI Business Pilot Demo {request_id[:8]}] Review Home profitability",
        description=(
            "Validate the human-approved Linear write path using fictional "
            "business data. This issue may be deleted after the test."
        ),
        team=LINEAR_DEFAULT_TEAM,
        proposed_priority=3,
        supporting_evidence=[
            "The issue is an integration test, not a production finding.",
            "No commercial action should be taken from this demo issue.",
        ],
    )


async def start_workflow(graph, thread_id: str) -> None:
    """Prepare a draft, pause, and print its approval payload."""
    result = await graph.ainvoke(
        {"draft": demo_draft(str(uuid4())).model_dump()},
        config={"configurable": {"thread_id": thread_id}},
    )
    interrupts = result.get("__interrupt__", [])
    if not interrupts:
        raise RuntimeError("Workflow did not pause for approval")

    print_heading("LINEAR ISSUE APPROVAL REQUIRED")
    print(f"Thread ID: {thread_id}")
    print(json.dumps(interrupts[0].value, indent=2))
    print("\nResume and decide interactively with:")
    print("uv run python scripts/check_approval_workflow.py resume")
    print("\nOr target this request explicitly with:")
    print(f"uv run python scripts/check_approval_workflow.py resume {thread_id}")


async def latest_paused_thread_id(graph, checkpointer) -> str:
    """Find the latest checkpointed thread still awaiting work."""
    thread_ids = []
    seen = set()
    async for checkpoint in checkpointer.alist(None, limit=100):
        thread_id = checkpoint.config["configurable"]["thread_id"]
        if thread_id not in seen:
            seen.add(thread_id)
            thread_ids.append(thread_id)

    for thread_id in thread_ids:
        snapshot = await graph.aget_state({"configurable": {"thread_id": thread_id}})
        if snapshot.next:
            return thread_id
    raise ValueError("No paused approval request was found")


def prompt_for_decision() -> str:
    """Read an explicit human decision from the terminal."""
    while True:
        choice = input("\nCreate this Linear demo issue? (y/n): ").strip().casefold()
        if choice in {"y", "yes"}:
            return "approve"
        if choice in {"n", "no"}:
            return "reject"
        print("Please enter y or n.")


def show_approval(snapshot, thread_id: str) -> None:
    """Show the exact validated content that an approval authorizes."""
    draft = LinearIssueDraft.model_validate(snapshot.values["draft"])
    print_heading("APPROVAL DECISION")
    print(f"Thread ID: {thread_id}")
    print(f"Title: {draft.title}")
    print(f"Team: {draft.team}")
    print(f"Proposed priority: {draft.proposed_priority}")
    print(f"\nFinal description:\n{draft.approved_description()}")


async def complete_workflow(
    checkpointer,
    thread_id: str,
    decision: str,
    *,
    retry_approved_action: bool = False,
) -> None:
    """Resume with rejection or with runtime-discovered Linear write tools."""
    config = {"configurable": {"thread_id": thread_id}}

    if decision == "reject":
        graph = build_approval_graph(checkpointer)
        result = await graph.ainvoke(
            Command(resume={"approved": False}),
            config=config,
        )
    else:
        adapter = create_mcp_adapter(
            include_duckdb=False,
            include_linear=True,
            include_linear_write=True,
        )
        async with adapter:
            tools = await adapter.list_tools()
            graph = build_approval_graph(checkpointer, tools)
            graph_input = (
                None if retry_approved_action else Command(resume={"approved": True})
            )
            result = await graph.ainvoke(graph_input, config=config)

    print_heading("APPROVAL WORKFLOW COMPLETED")
    print(f"Thread ID: {thread_id}")
    print(f"Decision: {decision}")
    print(f"Approved: {result.get('approved')}")
    print(f"Status: {result.get('status')}")
    if result.get("created_issue"):
        print("Created/verified issue:")
        print(json.dumps(result["created_issue"], indent=2, default=str))


async def main() -> None:
    """Start or resume the durable Linear approval workflow."""
    args = parse_args()
    CHECKPOINT_DB.parent.mkdir(parents=True, exist_ok=True)

    async with AsyncSqliteSaver.from_conn_string(str(CHECKPOINT_DB)) as checkpointer:
        graph = build_approval_graph(checkpointer)
        if args.command == "start":
            thread_id = args.thread_id or f"linear-demo-{uuid4()}"
            await start_workflow(graph, thread_id)
            return

        thread_id = args.thread_id or await latest_paused_thread_id(
            graph,
            checkpointer,
        )
        config = {"configurable": {"thread_id": thread_id}}
        snapshot = await graph.aget_state(config)
        if not snapshot.next:
            raise ValueError(f"No paused approval request found for {thread_id!r}")

        retry_approved_action = snapshot.values.get("approved") is True
        if retry_approved_action:
            print_heading("RETRYING PREVIOUSLY APPROVED ACTION")
            print(f"Thread ID: {thread_id}")
            print("The draft was already approved; no new approval is requested.")
            decision = "approve"
        else:
            show_approval(snapshot, thread_id)
            decision = args.decision or prompt_for_decision()

        await complete_workflow(
            checkpointer,
            thread_id,
            decision,
            retry_approved_action=retry_approved_action,
        )


if __name__ == "__main__":
    asyncio.run(main())
